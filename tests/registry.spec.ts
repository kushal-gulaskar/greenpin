import {test,expect,type Page} from '@playwright/test'
async function register(page:Page,name:string){
 await page.goto('/register')
 await page.getByLabel('Common name').fill(name)
 await page.getByLabel('Species',{exact:true}).selectOption('Neem')
 await page.getByLabel('Tree photograph').setInputFiles('public/images/canopy.jpg')
 await page.getByLabel('Latitude').fill('12.96')
 await page.getByLabel('Longitude').fill('77.59')
 await page.getByLabel('Location description').fill('Community garden')
 await page.getByRole('button',{name:'Save tree'}).click()
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
 return page.url().split('/').pop()!
}
test('empty registration stays on form and denied GPS allows manual entry',async({page})=>{
 await page.addInitScript(()=>Object.defineProperty(navigator,'geolocation',{value:{getCurrentPosition:(_ok:unknown,fail:()=>void)=>fail()}}))
 await page.goto('/register')
 await page.getByRole('button',{name:'Save tree'}).click()
 await expect(page.getByLabel('Common name')).toBeFocused()
 await page.getByRole('button',{name:'Capture GPS location'}).click()
 await expect(page.getByRole('status')).toContainText('Enter coordinates manually')
 await page.getByLabel('Latitude').fill('23')
 await expect(page.getByLabel('Latitude')).toHaveValue('23')
})
test('unique registrations persist with photos, search and details',async({page})=>{
 const first=await register(page,'Garden neem')
 const second=await register(page,'Courtyard neem')
 expect(first).toMatch(/^[a-f0-9-]{36}$/);expect(first).not.toBe(second)
 await page.reload()
 await page.goto('/trees')
 await page.getByLabel('Filter by source').selectOption('local')
 await expect(page.locator('article')).toHaveCount(2)
 await page.getByLabel('Search trees').fill('Garden neem')
 await page.getByRole('link',{name:'View details'}).click()
 await expect(page).toHaveURL(new RegExp(first+'$'))
 await expect(page.getByText('12.96, 77.59')).toBeVisible()
 await expect.poll(()=>page.getByAltText('Garden neem').evaluate(el=>(el as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
})
test('mobile navigation opens local tree locations',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/')
 await page.getByRole('button',{name:'Toggle navigation'}).click()
 await page.getByRole('navigation').getByText('Explore map').click()
 await expect(page.getByText('Tree locations',{exact:true})).toBeVisible()
 await page.getByRole('link',{name:/Neem.*Cubbon/}).click()
 await expect(page.getByRole('heading',{name:'Neem',exact:true})).toBeVisible()
})